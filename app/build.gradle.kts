/**
 * Release signing is configured from a keystore supplied OUTSIDE the repository:
 * either environment variables or a `keystore.properties` file that is git-ignored.
 * If none is present the release build falls back to the debug signing identity and
 * says so in the build log. No secret is ever committed.
 */
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(key: String, env: String): String? =
    (keystoreProps.getProperty(key) ?: System.getenv(env))?.takeIf { it.isNotBlank() }

